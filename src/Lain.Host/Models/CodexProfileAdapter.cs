using System.Text.Json;
using System.Security.Cryptography;
using System.Text;
using System.Globalization;
using Lain.Core;
using Lain.Host.Providers;

namespace Lain.Host.Models;

public record CodexProfileArtifacts(string ConfigFileName, string Configuration, string CatalogFileName, string Catalog, string[] LaunchArguments, long Revision,
    ModelCompatibilityManifestDto? Compatibility = null, string? ProfileId = null, string? GenerationId = null);

/// <summary>Pure export: installation is an explicit caller operation. Never reads or changes Codex's base config.</summary>
public sealed class CodexProfileAdapter(ModelsService models, ModelCompatibilityCatalog? compatibility = null, ProviderCatalogRegistry? registry = null,
    CollectionRouterExportProof? routerProof = null)
{
    public const string VerifiedVersion = ModelCompatibilityCatalog.ClientVersion;

    public CodexProfileArtifacts Generate(string profileId, long revision, string absoluteLainExecutable, string absoluteCatalogPath,
        string proxyBaseUrl = "http://127.0.0.1:18417/v1", bool enableLainModelPicker = false)
    {
        if (!Path.IsPathFullyQualified(absoluteLainExecutable) || !Path.IsPathFullyQualified(absoluteCatalogPath))
            throw new ArgumentException("Codex auth executable and catalog paths must be absolute.");
        if (!Uri.TryCreate(proxyBaseUrl, UriKind.Absolute, out var endpoint) || !endpoint.IsLoopback || endpoint.Scheme != "http" ||
            !string.IsNullOrEmpty(endpoint.UserInfo) || !string.IsNullOrEmpty(endpoint.Query) || !string.IsNullOrEmpty(endpoint.Fragment))
            throw new ArgumentException("Codex must connect to the local lain proxy without embedded credentials.");
        var resolved = models.ResolveForApply(profileId, revision);
        var routes = resolved.Routes.Where(x => x.Visible && x.Enabled).ToArray();
        var manifest = (compatibility ?? new ModelCompatibilityCatalog()).Manifest(routes);
        var selectable = routes.Where(route => !IsInternalReview(route)).ToArray();
        if (selectable.Length == 0 || routes.Any(route => route.Id == resolved.Profile.DefaultRouteId && IsInternalReview(route)))
            throw new ArgumentException("An internal Codex review model cannot be the profile's default model. Select a normal model.");
        var selected = selectable.SingleOrDefault(x => x.Id == resolved.Profile.DefaultRouteId) ?? selectable[0];
        var catalogRegistry = registry ?? new ProviderCatalogRegistry();
        var routers = enableLainModelPicker ? (resolved.Configuration.CollectionRouters ?? []).Where(r => r.Enabled && r.ProfileId == profileId).ToArray() : [];
        if (routers.Length > 0 && (routerProof is null || !routerProof.Matches(resolved.Configuration with { Routes = resolved.Routes }, profileId)))
            throw new ArgumentException("Router catalog export proof is missing or stale; recompile this profile's current transports.");
        foreach (var router in routers)
            if (routerProof is null || !routerProof.Routers.TryGetValue(router.Alias, out var binding) || binding.Id != router.Id || binding.ProfileId != profileId)
                throw new ArgumentException("Router catalog export requires the current qualified profile bindings.");
        // TOML basic strings accept these JSON escapes for the paths and labels we emit.
        static string Quote(string value) => JsonSerializer.Serialize(value);
        var config = $"""
            # Generated by lain for Codex CLI {VerifiedVersion}; configuration revision {revision}.
            # Client schema/tool fixture qualification only; provider capabilities remain source scoped and may be unknown.
            model = {Quote(selected.Alias)}
            model_provider = "lain"
            model_catalog_json = {Quote(absoluteCatalogPath)}
            # Native Responses search requires separate gateway support; ordinary function/MCP tools remain configured by Codex.
            web_search = "disabled"

            [model_providers.lain]
            name = "lain"
            base_url = {Quote(proxyBaseUrl)}
            wire_api = "responses"

            [model_providers.lain.auth]
            command = {Quote(absoluteLainExecutable)}
            args = ["auth", "token", "--audience", "codex"]
            timeout_ms = 5000
            refresh_interval_ms = 300000
            """ + "\n";
        // Capabilities not established by RouteDto are deliberately not advertised.
        // Supported model metadata can be added by a qualified catalog source later.
        var catalogDocument = new Dictionary<string, object>
        {
            ["models"] = routes.Select((route, index) => CatalogEntry(route.Alias, DisplayName(route, catalogRegistry),
                Description(route, catalogRegistry), IsInternalReview(route), index))
                .Concat(routers.Select((router, index) => CatalogEntry(router.Alias, "Automatisch · " + RouterGroupName(router, resolved.Configuration, catalogRegistry), "Ordered selection for a new conversation; fixed model and account thereafter. No cross-route retry.", false, routes.Length + index))).ToArray()
        };
        // Versioned lain client extension, not a native Codex catalog field. Callers opt in
        // only for the separately qualified patched CLI and its generated --profile lain.
        if (enableLainModelPicker)
            catalogDocument["lain_model_picker"] = new { schema_version = 1, groups = PickerGroups(resolved.Configuration, selectable, catalogRegistry, routers) };
        var catalog = JsonSerializer.Serialize(catalogDocument, new JsonSerializerOptions { WriteIndented = true });
        var generation = Convert.ToHexString(SHA256.HashData(Encoding.UTF8.GetBytes(
            profileId + "\n" + revision.ToString(CultureInfo.InvariantCulture) + "\n" + config + "\n" + catalog))).ToLowerInvariant();
        return new("lain.config.toml", config, Path.GetFileName(absoluteCatalogPath), catalog, ["--no-daemon", "--profile", "lain"], revision, manifest, profileId, generation);
    }

    private static object CatalogEntry(string slug, string label, string description, bool hidden, int priority) => new
    {
        slug, display_name = label, description,
        default_reasoning_level = "none", supported_reasoning_levels = Array.Empty<object>(),
        shell_type = "unified_exec", visibility = hidden ? "hide" : "list", supported_in_api = true, priority,
        base_instructions = "You are a coding assistant.", supports_reasoning_summaries = false,
        support_verbosity = false, truncation_policy = new { mode = "tokens", limit = 10000 },
        supports_search_tool = false, tool_mode = (string?)null,
        experimental_supported_tools = Array.Empty<string>(), input_modalities = new[] { "text" }
    };

    private object[] PickerGroups(ConfigurationDto configuration, RouteDto[] routes, ProviderCatalogRegistry catalog, CollectionRouterDto[] routers)
    {
        var byId = routes.ToDictionary(route => route.Id, StringComparer.Ordinal);
        var groups = new List<object>();
        void Add(string id, string name, IEnumerable<string> routeIds)
        {
            var aliases = routeIds.Where(byId.ContainsKey).Select(routeId => byId[routeId].Alias).Distinct(StringComparer.Ordinal).ToArray();
            if (aliases.Length == 0) return;
            if (Encoding.UTF8.GetByteCount(id) > 256 || Encoding.UTF8.GetByteCount(name) > 1024 ||
                string.IsNullOrWhiteSpace(name) || id.Any(char.IsControl) || name.Any(char.IsControl))
                throw new ArgumentException("The lain Codex model picker requires single-line group IDs up to 256 UTF-8 bytes and names up to 1024 UTF-8 bytes. Stored names are preserved; shorten the affected group label before export.");
            groups.Add(new { id, name, router_model = routers.SingleOrDefault(router => router.GroupId == id)?.Alias, models = aliases });
        }
        foreach (var collection in configuration.Collections ?? [])
            Add("collection:" + collection.Id, collection.Name, collection.RouteIds);
        if (routers.SingleOrDefault(router => router.GroupId == "policy:free") is { } freeRouter)
            Add("policy:free", "Free", routerProof!.Routers[freeRouter.Alias].RouteIds);
        // Free is emitted only from the current compiler-created router proof above.
        // A hypothetical policy override cannot make an existing alias free; custom
        // collection names retain their stored meaning without cost guarantees.
        foreach (var provider in routes.GroupBy(route => route.Provider, StringComparer.OrdinalIgnoreCase)
            .OrderBy(group => group.Key, StringComparer.OrdinalIgnoreCase))
            Add("provider:" + provider.Key.ToLowerInvariant(), ServiceName(provider.First(), catalog), provider.Select(route => route.Id));
        if (groups.Count > 128)
            throw new ArgumentException("The lain Codex model picker supports at most 128 non-empty groups. Reduce the selected profile's provider or collection views.");
        return groups.ToArray();
    }

    // This is the native internal approval-review model, never a collection auto-router.
    // Match the upstream identity and canonical service, not a user-controlled alias.
    private static bool IsInternalReview(RouteDto route) => route.Provider == "codex" && route.UpstreamModel == "codex-auto-review";

    private static string RouterGroupName(CollectionRouterDto router, ConfigurationDto configuration, ProviderCatalogRegistry catalog) =>
        router.GroupId == "policy:free" ? "Free" : router.GroupId.StartsWith("collection:", StringComparison.Ordinal)
            ? (configuration.Collections ?? []).Single(collection => "collection:" + collection.Id == router.GroupId).Name
            : catalog.Find(router.GroupId[9..])?.Name ?? router.GroupId[9..];

    private static ProviderRouteDescriptorDto? PresentationModel(RouteDto route, ProviderCatalogRegistry catalog)
    {
        var provider = catalog.Find(route.Provider);
        var template = provider?.Routes.SingleOrDefault(model => model.Id == route.ProviderRouteId);
        if (template is not null) return template.Model == route.UpstreamModel ? template : null;
        // Imported routes may use a documented name only when the model has one unambiguous template.
        var candidates = provider?.Routes.Where(model => model.Model == route.UpstreamModel).ToArray();
        return candidates?.Length == 1 ? candidates[0] : null;
    }

    private static string ServiceName(RouteDto route, ProviderCatalogRegistry catalog) => catalog.Find(route.Provider)?.Name ?? route.Provider switch
    {
        "codex" => "Codex", "commandcode" => "Command Code", "kimi" => "Kimi",
        "xiaomi-mimo" => "Xiaomi MiMo", "zai" => "Z.ai", _ => route.Provider
    };

    private static string DisplayName(RouteDto route, ProviderCatalogRegistry catalog) =>
        $"{(IsInternalReview(route) ? "Codex Auto Review" : PresentationModel(route, catalog)?.Name ?? route.UpstreamModel)} · {ServiceName(route, catalog)}";

    private static string Description(RouteDto route, ProviderCatalogRegistry catalog)
    {
        if (IsInternalReview(route)) return "Internal Codex approval review model; unavailable for ordinary model selection.";
        var model = PresentationModel(route, catalog);
        var manufacturer = string.IsNullOrWhiteSpace(model?.Manufacturer) ? "" : $" Manufacturer: {model.Manufacturer}.";
        return $"Model: {model?.Name ?? route.UpstreamModel}. Service: {ServiceName(route, catalog)}.{manufacturer}";
    }
}
